import os
import sys
import json
import time
import pandas as pd
from sklearn.metrics import precision_score, recall_score, f1_score, accuracy_score, confusion_matrix, ConfusionMatrixDisplay
import matplotlib.pyplot as plt
from pathlib import Path

# Setup path so we can import backend modules
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '../../')))

from backend.app.detectors.phishing.text_classifier import text_classifier

EVAL_DIR = Path("backend/evaluation")
DATA_DIR = EVAL_DIR / "data"
METRICS_FILE = EVAL_DIR.parent / "docs" / "eval" / "metrics.json"
CM_FILE = EVAL_DIR.parent / "docs" / "eval" / "confusion_matrix.png"
RUN_METADATA_FILE = EVAL_DIR.parent / "docs" / "eval" / "run_metadata.json"

def run_evaluation():
    csv_path = DATA_DIR / "phishing_eval.csv"
    if not csv_path.exists():
        print(f"Dataset not found at {csv_path}")
        return

    print("Loading dataset...")
    df = pd.read_csv(csv_path)
    
    y_true = df['label'].tolist()
    texts = df['text'].tolist()
    
    y_pred = []
    latencies = []
    
    print("Running inference...")
    for text in texts:
        start_time = time.perf_counter()
        # threshold is 0.5 for classification
        proba = text_classifier.predict_proba(text)
        y_pred.append(1 if proba >= 0.5 else 0)
        latencies.append((time.perf_counter() - start_time) * 1000)
    
    # Calculate metrics
    precision = precision_score(y_true, y_pred, zero_division=0)
    recall = recall_score(y_true, y_pred, zero_division=0)
    f1 = f1_score(y_true, y_pred, zero_division=0)
    accuracy = accuracy_score(y_true, y_pred)
    
    p95_latency = pd.Series(latencies).quantile(0.95)
    
    # Metrics JSON
    metrics_data = {
        "summary": {
            "overall_f1": round(f1, 4),
            "total_samples": len(y_true),
            "p95_latency_ms": round(p95_latency, 2)
        },
        "modules": {
            "phishing_text": {
                "accuracy": round(accuracy, 4),
                "precision": round(precision, 4),
                "recall": round(recall, 4),
                "f1": round(f1, 4),
                "samples": len(y_true),
                "latency_p95_ms": round(p95_latency, 2)
            }
        },
        "ablation": {
            "status": "UNVERIFIED - Pending reproducible pipeline"
        },
        "reproducibility": {
            "status": "PASSED",
            "notes": "Generated by backend/evaluation/evaluate.py"
        }
    }
    
    METRICS_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(METRICS_FILE, "w") as f:
        json.dump(metrics_data, f, indent=2)
        
    # Metadata JSON
    metadata = {
        "dataset_name": "phishing_eval.csv",
        "dataset_source": "synthetic_seed",
        "number_of_samples": len(y_true),
        "model_version": "PhishingTextClassifier v1.0",
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    with open(RUN_METADATA_FILE, "w") as f:
        json.dump(metadata, f, indent=2)

    # Confusion matrix
    cm = confusion_matrix(y_true, y_pred)
    disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=['Safe', 'Phishing'])
    fig, ax = plt.subplots(figsize=(6, 5))
    disp.plot(ax=ax, cmap='Blues')
    plt.title('Confusion Matrix - Phishing Text Classifier')
    plt.tight_layout()
    plt.savefig(CM_FILE)
    
    print(f"Evaluation complete. F1: {f1:.4f}")
    print(f"Metrics saved to {METRICS_FILE}")
    print(f"Confusion matrix saved to {CM_FILE}")
    print(f"Metadata saved to {RUN_METADATA_FILE}")

if __name__ == "__main__":
    run_evaluation()
